#!/usr/bin/env python3
"""Generates src/dsp/dsp_tables.c and src/platform/uac_fir.h with exact integer lookup tables."""

import math
from pathlib import Path

FS = 24_000_000.0 / 544.0  # 44117.64705882353 Hz (exact AC791N ALNK0 sample rate)
NOTE_LEN = 141
CUTOFF_LEN = 257
SINE_LEN = 1024

FC_MIN = 32.70319566257483  # C1
FC_MAX = 21000.0


def fmt_array(vals: list[int], per_line: int = 8, hex_fmt: bool = False) -> str:
    lines = []
    for i in range(0, len(vals), per_line):
        chunk = vals[i : i + per_line]
        if hex_fmt:
            s = ", ".join(f"0x{v:08X}u" for v in chunk)
        else:
            s = ", ".join(str(v) for v in chunk)
        lines.append(f"    {s},")
    return "\n".join(lines)


def bessel_i0(x: float) -> float:
    term = 1.0
    total = 1.0
    half_x_sq = 0.25 * x * x
    k = 1
    while term > 1e-16 * total:
        term *= half_x_sq / (k * k)
        total += term
        k += 1
    return total


def gen_uac_fir(root: Path) -> None:
    """Generates 16-tap x 160-phase symmetric polyphase Kaiser-sinc FIR for 44.1 -> 48 kHz UAC1."""
    n_taps = 16
    l_phases = 160
    m_step = 147
    q_bits = 30
    q_one = 1 << q_bits
    fc = 0.45       # Cutoff in cycles per 44.1 kHz input sample (~19.85 kHz)
    beta = 7.2      # Kaiser beta (~76-88 dB stopband image attenuation)
    radius = n_taps / 2.0
    inv_i0 = 1.0 / bessel_i0(beta)

    rows = []
    for ph in range(l_phases // 2):
        raw = []
        for k in range(n_taps):
            # tau(ph, k) = 7 - k + (ph + 0.5) / 160 -> exact mirror tau(159 - ph, 15 - k) = -tau(ph, k)
            tau = (n_taps // 2 - 1) - k + (ph + 0.5) / l_phases
            u = 2.0 * fc * tau
            sinc = 1.0 if abs(u) < 1e-12 else math.sin(math.pi * u) / (math.pi * u)
            r_norm = min(1.0, abs(tau) / radius)
            win = bessel_i0(beta * math.sqrt(1.0 - r_norm * r_norm)) * inv_i0
            raw.append(2.0 * fc * sinc * win)
        s = sum(raw)
        q_row = [int(round((v / s) * q_one)) for v in raw]
        # Guarantee exact Q30 unity DC gain per phase so zero phase-ripple occurs on steady signals
        q_row[n_taps // 2 - 1] += q_one - sum(q_row)
        rows.append(q_row)

    row_lines = []
    for ph, q_row in enumerate(rows):
        row_s = ", ".join(f"{v:10d}" for v in q_row)
        row_lines.append(f"    /* ph {ph:2d} */ {{ {row_s} }},")

    hdr_src = f"""/* SPDX-License-Identifier: MPL-2.0
 * Auto-generated by tools/gen_dsp_tables.py — DO NOT EDIT BY HAND.
 * 160/147 polyphase Kaiser-windowed sinc FIR (16 taps/phase, fc=0.45, beta=7.2, Q30)
 * for USB Audio Class 1 44.1 kHz -> 48 kHz resampling (felucca-bsp usb.c).
 */
#ifndef ADRIFT_UAC_FIR_H
#define ADRIFT_UAC_FIR_H

#include <stdint.h>

#define UAC_FIR_N {n_taps}u
#define UAC_FIR_L {l_phases}u
#define UAC_FIR_Q {q_bits}
#define UAC_FIR_M {m_step}u

static const int32_t UAC_FIR[UAC_FIR_L / 2u][UAC_FIR_N] = {{
{chr(10).join(row_lines)}
}};

#endif /* ADRIFT_UAC_FIR_H */
"""
    fir_path = root / "src" / "platform" / "uac_fir.h"
    fir_path.write_text(hdr_src)
    print(f"Generated {fir_path} ({len(hdr_src)} bytes)")


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    out_path = root / "src" / "dsp" / "dsp_tables.c"

    sine_q15 = [int(round(32767.0 * math.sin(2.0 * math.pi * i / SINE_LEN))) for i in range(SINE_LEN + 1)]
    sine_q15[-1] = sine_q15[0]

    phase_inc = []
    period_q16 = []
    freq_q8 = []
    for n in range(NOTE_LEN):
        f0 = 440.0 * (2.0 ** ((n - 69.0) / 12.0))
        f_clamped = min(f0, FS * 0.48)
        inc = int(round((f_clamped / FS) * (2.0 ** 32)))
        inc = min(inc, 0x7AE147AE)
        per = int(round((FS / f0) * 65536.0))
        fq8 = int(round(f0 * 256.0))
        phase_inc.append(inc)
        period_q16.append(min(per, 0xFFFFFFFF))
        freq_q8.append(min(fq8, 0xFFFFFFFF))

    cutoff_fc_q8 = []
    svf_g_q16 = []
    onepole_a_q15 = []
    ratio = FC_MAX / FC_MIN
    for i in range(CUTOFF_LEN):
        fc = FC_MIN * (ratio ** (i / (CUTOFF_LEN - 1)))
        fc = min(fc, FS * 0.485)
        g = math.tan(math.pi * fc / FS)
        a = 1.0 - math.exp(-2.0 * math.pi * fc / FS)
        cutoff_fc_q8.append(int(round(fc * 256.0)))
        svf_g_q16.append(int(round(g * 65536.0)))
        onepole_a_q15.append(max(1, min(32767, int(round(a * 32768.0)))))

    # atan(u) for u = i / 64.0 in [0..1], stored in Q16 radians (pi/2 * 65536 = 102944)
    atan_q16 = [int(round(math.atan(i / 64.0) * 65536.0)) for i in range(65)]

    c_src = f'''/* Auto-generated by tools/gen_dsp_tables.py — DO NOT EDIT BY HAND.
 * Exact integer DSP tables referenced to AC791N I2S Fs = 24000000 / 544 = {FS:.6f} Hz.
 */
#include "dsp_math.h"

#if defined(__GNUC__) || defined(__clang__)
#define DSP_NOINLINE __attribute__((noinline))
#else
#define DSP_NOINLINE
#endif

const int16_t DSP_HOT_DATA g_dsp_sine_q15[DSP_SINE_LUT_LEN + 1] = {{
{fmt_array(sine_q15, 12)}
}};

const uint32_t g_dsp_note_phase_inc[DSP_NOTE_TABLE_LEN] = {{
{fmt_array(phase_inc, 6, hex_fmt=True)}
}};

const uint32_t g_dsp_note_period_q16[DSP_NOTE_TABLE_LEN] = {{
{fmt_array(period_q16, 6, hex_fmt=True)}
}};

const uint32_t g_dsp_note_freq_q8[DSP_NOTE_TABLE_LEN] = {{
{fmt_array(freq_q8, 6, hex_fmt=True)}
}};

const uint32_t g_dsp_cutoff_fc_q8[DSP_CUTOFF_LUT_LEN] = {{
{fmt_array(cutoff_fc_q8, 8)}
}};

const uint32_t g_dsp_svf_g_q16[DSP_CUTOFF_LUT_LEN] = {{
{fmt_array(svf_g_q16, 8)}
}};

const uint16_t g_dsp_onepole_a_q15[DSP_CUTOFF_LUT_LEN] = {{
{fmt_array(onepole_a_q15, 10)}
}};

const uint16_t g_dsp_atan_q15[65] = {{
{fmt_array(atan_q16, 10)}
}};

/* ---- Out-of-line 64-bit helpers (pi32v2 mul64-near-load safe) ---- */

DSP_NOINLINE int32_t dsp_mul_q30(int32_t a, int32_t b) {{
    return (int32_t)(((int64_t)a * (int64_t)b) >> 30);
}}

DSP_NOINLINE int32_t dsp_mul_q28(int32_t a, int32_t b) {{
    return (int32_t)(((int64_t)a * (int64_t)b) >> 28);
}}

DSP_NOINLINE int32_t dsp_mul_q24(int32_t a, int32_t b) {{
    return (int32_t)(((int64_t)a * (int64_t)b) >> 24);
}}

DSP_NOINLINE int32_t dsp_mul_q16(int32_t a, int32_t b) {{
    return (int32_t)(((int64_t)a * (int64_t)b) >> 16);
}}

DSP_NOINLINE uint32_t dsp_umul_q16(uint32_t a, uint32_t b) {{
    return (uint32_t)(((uint64_t)a * (uint64_t)b) >> 16);
}}

DSP_NOINLINE uint32_t dsp_div_u32_q16(uint32_t num, uint32_t den) {{
    if (den == 0u) return 0xFFFFFFFFu;
    return (uint32_t)(((uint64_t)num << 16) / (uint64_t)den);
}}

static DSP_NOINLINE uint32_t interp_convex_u32(uint32_t y0, uint32_t y1, uint32_t frac_256) {{
    /* Parabolic-corrected interpolation for exponential 2^(x/12) tables (< 0.02 cents error) */
    if (y1 >= y0) {{
        uint32_t d = y1 - y0;
        uint32_t lin = y0 + (uint32_t)(((uint64_t)d * frac_256) >> 8);
        uint32_t bow = (uint32_t)(((uint64_t)d * frac_256 * (256u - frac_256) * 19u) >> 26);
        return lin - bow;
    }} else {{
        uint32_t d = y0 - y1;
        uint32_t lin = y0 - (uint32_t)(((uint64_t)d * frac_256) >> 8);
        uint32_t bow = (uint32_t)(((uint64_t)d * frac_256 * (256u - frac_256) * 19u) >> 26);
        return lin - bow;
    }}
}}

uint32_t dsp_pitch_to_phase_inc(int32_t pitch_q8) {{
    if (pitch_q8 <= 0) return g_dsp_note_phase_inc[0];
    int32_t max_p = (DSP_NOTE_TABLE_LEN - 2) << 8;
    if (pitch_q8 >= max_p) return g_dsp_note_phase_inc[DSP_NOTE_TABLE_LEN - 1];
    uint32_t idx  = (uint32_t)(pitch_q8 >> 8);
    uint32_t frac = (uint32_t)(pitch_q8 & 0xFF);
    return interp_convex_u32(g_dsp_note_phase_inc[idx], g_dsp_note_phase_inc[idx + 1u], frac);
}}

uint32_t dsp_pitch_to_period_q16(int32_t pitch_q8) {{
    if (pitch_q8 <= 0) return g_dsp_note_period_q16[0];
    int32_t max_p = (DSP_NOTE_TABLE_LEN - 2) << 8;
    if (pitch_q8 >= max_p) return g_dsp_note_period_q16[DSP_NOTE_TABLE_LEN - 1];
    uint32_t idx  = (uint32_t)(pitch_q8 >> 8);
    uint32_t frac = (uint32_t)(pitch_q8 & 0xFF);
    return interp_convex_u32(g_dsp_note_period_q16[idx], g_dsp_note_period_q16[idx + 1u], frac);
}}

uint32_t dsp_pitch_to_freq_q8(int32_t pitch_q8) {{
    if (pitch_q8 <= 0) return g_dsp_note_freq_q8[0];
    int32_t max_p = (DSP_NOTE_TABLE_LEN - 2) << 8;
    if (pitch_q8 >= max_p) return g_dsp_note_freq_q8[DSP_NOTE_TABLE_LEN - 1];
    uint32_t idx  = (uint32_t)(pitch_q8 >> 8);
    uint32_t frac = (uint32_t)(pitch_q8 & 0xFF);
    return interp_convex_u32(g_dsp_note_freq_q8[idx], g_dsp_note_freq_q8[idx + 1u], frac);
}}

uint32_t dsp_cutoff_to_fc_q8(int32_t cutoff_1023) {{
    int32_t c = dsp_clamp_i32(cutoff_1023, 0, 1023);
    uint32_t idx  = (uint32_t)(c >> 2);
    uint32_t frac = (uint32_t)(c & 3);
    uint32_t y0 = g_dsp_cutoff_fc_q8[idx];
    uint32_t y1 = g_dsp_cutoff_fc_q8[idx + 1u];
    return y0 + (((y1 - y0) * frac) >> 2);
}}

uint32_t dsp_cutoff_to_svf_g_q16(int32_t cutoff_1023) {{
    int32_t c = dsp_clamp_i32(cutoff_1023, 0, 1023);
    uint32_t idx  = (uint32_t)(c >> 2);
    uint32_t frac = (uint32_t)(c & 3);
    uint32_t y0 = g_dsp_svf_g_q16[idx];
    uint32_t y1 = g_dsp_svf_g_q16[idx + 1u];
    return y0 + (((y1 - y0) * frac) >> 2);
}}

uint16_t dsp_cutoff_to_onepole_a_q15(int32_t cutoff_1023) {{
    int32_t c = dsp_clamp_i32(cutoff_1023, 0, 1023);
    uint32_t idx  = (uint32_t)(c >> 2);
    uint32_t frac = (uint32_t)(c & 3);
    uint32_t y0 = g_dsp_onepole_a_q15[idx];
    uint32_t y1 = g_dsp_onepole_a_q15[idx + 1u];
    return (uint16_t)(y0 + (((y1 - y0) * frac) >> 2));
}}

uint32_t dsp_atan2_pos_q16(uint32_t num, uint32_t den) {{
    const uint32_t half_pi_q16 = 102944u; /* round(pi / 2 * 65536) */
    if (num == 0u) return 0u;
    if (den == 0u) return half_pi_q16;
    bool swapped = false;
    if (num > den) {{
        uint32_t tmp = num;
        num = den;
        den = tmp;
        swapped = true;
    }}
    /* u_q16 in [0 .. 65536] */
    uint32_t u_q16 = dsp_div_u32_q16(num, den);
    if (u_q16 >= 65536u) {{
        return swapped ? (half_pi_q16 - g_dsp_atan_q15[64]) : g_dsp_atan_q15[64];
    }}
    uint32_t idx  = u_q16 >> 10;          /* 0 .. 63 */
    uint32_t frac = u_q16 & 0x3FFu;       /* 0 .. 1023 */
    uint32_t a0   = g_dsp_atan_q15[idx];
    uint32_t a1   = g_dsp_atan_q15[idx + 1u];
    uint32_t ang  = a0 + (((a1 - a0) * frac) >> 10);
    return swapped ? (half_pi_q16 - ang) : ang;
}}
'''
    out_path.write_text(c_src)
    print(f"Generated {out_path} ({len(c_src)} bytes)")
    gen_uac_fir(root)


if __name__ == "__main__":
    main()
